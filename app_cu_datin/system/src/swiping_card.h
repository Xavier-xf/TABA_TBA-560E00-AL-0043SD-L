/*********************************************************************************************************
 * 文 件 名 : swiping_card.h
 * 功能说明 : 刷卡功能核心头文件，定义刷卡模式枚举、刷卡状态结构体及对外接口声明
 * 备    注 : 依赖ak_common.h提供的时间结构体等基础定义
 *********************************************************************************************************/
#ifndef SWIPING_CARD_H
#define SWIPING_CARD_H
#include "ak_common.h"

/*********************************************************************************************************
 * 枚 举 名 : SWIPING_CARD_MODE
 * 功能说明 : 刷卡功能的工作模式枚举，定义刷卡流程中不同的状态阶段
 * 备    注 : 各模式按刷卡业务逻辑的状态流转顺序定义
 *********************************************************************************************************/
typedef enum
{
	CARD_IDLE_MODE,					// 刷卡空闲模式：未检测到刷卡数据，等待刷卡
	CARD_SWIPING_CARD_MODE,			// 刷卡验证模式：已接收刷卡数据，正在校验卡片合法性
	CARD_ADD_CARD_MODE,				// 添加卡片模式：处于新增卡片的业务流程中
	CARD_TAG_FILL_MODE,				// TAG填充模式：卡管理页刷已保存卡后填充TAG编号
	CARD_UNLOCK_MODE,				// 解锁模式：卡片验证通过，执行开门动作的阶段
	CARD_SWIPING_CARD_PROCESS_MODE, // 刷卡处理中模式：非法卡/验证失败后的短暂忙状态
	CARD_ADD_CARD_PROCESS_MODE		// 添加卡片处理中模式：添加卡片成功/失败后的短暂忙状态
} SWIPING_CARD_MODE;

/*********************************************************************************************************
 * 结 构 名 : STR_SwipingCardClass
 * 功能说明 : 刷卡功能状态管理结构体，存储刷卡模式、时间戳、显示标记等核心状态
 * 备    注 : 全局唯一实例SwipingCard用于管理整个刷卡流程的状态
 *********************************************************************************************************/
typedef struct
{
	SWIPING_CARD_MODE mode;		   // 当前刷卡工作模式
	struct ak_timeval unlock_time; // 解锁动作的时间戳（用于控制开门时长）
	struct ak_timeval busy_time;   // 忙状态的时间戳（用于控制忙状态时长）
	bool success_show;			   // 标记是否需要显示添加卡片成功的文字提示
	bool tag_fill_request;		   // 标记卡管理页当前刷卡用于填充TAG而不是新增卡
	char string_buf[11][32];
} STR_SwipingCardClass;

/*********************************************************************************************************
 * 变 量 名 : SwipingCard
 * 功能说明 : 刷卡功能全局状态变量，存储当前刷卡流程的所有状态信息
 * 备    注 : 外部模块可通过该变量读取/修改刷卡状态
 *********************************************************************************************************/
extern STR_SwipingCardClass SwipingCard;

/*********************************************************************************************************
 * 函 数 名 : swiping_card_event_detect
 * 功能说明 : 刷卡事件检测核心函数，接收串口刷卡数据并处理不同模式下的业务逻辑
 * 形    参 : card_fd_serial - 刷卡模块对应的串口文件描述符
 * 返 回 值 : 无
 * 备    注 : 需在主循环中周期性调用，处理数据接收、模式切换、音效播放、开门控制等逻辑
 *********************************************************************************************************/
extern void swiping_card_event_detect(int card_fd_serial);

/*********************************************************************************************************
 * 函 数 名 : unit_number_exist
 * 功能说明 : 检查指定的单元号是否存在于已配置的单元号列表中
 * 形    参 : unit_number - 待检查的单元号数值
 * 返 回 值 : bool - 单元号存在返回true，不存在返回false
 * 备    注 : 用于刷卡/添加卡片流程中验证单元号合法性
 *********************************************************************************************************/
extern bool unit_number_exist(int unit_number);

#endif
