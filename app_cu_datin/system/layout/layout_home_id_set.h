#ifndef LAYOUT_HOME_ID_SET_H
#define LAYOUT_HOME_ID_SET_H

/*********************************************************************************************************
 * 枚举名称 : ENUM_HOME_ID_SET_DIALOG_BOX
 * 功能说明 : 房号设置功能中4个输入框的枚举定义
 * 设计说明 : 用于标识不同的房号输入框（M1-M4），以及输入框总数，便于数组索引和范围判断
 *********************************************************************************************************/
typedef enum
{
	HOME_ID_SET_M1_DIALOG_BOX = 0, // 房号设置第一个输入框（M1）
	HOME_ID_SET_M2_DIALOG_BOX,	   // 房号设置第二个输入框（M2）
	HOME_ID_SET_M3_DIALOG_BOX,	   // 房号设置第三个输入框（M3）
	HOME_ID_SET_M4_DIALOG_BOX,	   // 房号设置第四个输入框（M4）
	HOME_ID_SET_TOTAL_DIALOG_BOX   // 房号输入框总数（固定为4），用于循环/范围校验
} ENUM_HOME_ID_SET_DIALOG_BOX;

/*********************************************************************************************************
 * 枚举名称 : SET_HOME_ID_STATUS
 * 功能说明 : 房号设置操作的状态枚举
 * 设计说明 : 标识房号设置的结果状态，用于UI提示显示和逻辑分支判断
 *********************************************************************************************************/
typedef enum
{
	HOME_ID_SET_STATUS_NONE,	// 无状态（初始值/状态已清除）
	HOME_ID_SET_STATUS_SUCCESS, // 房号设置成功
	HOME_ID_SET_STATUS_FAIL,	// 房号设置失败（如重复、格式错误等）
	HOME_ID_SET_STATUS_EXISTED, // 房号已存在（与已有房号冲突）
	HOME_ID_SET_STATUS_			// 预留状态位（扩展用）
} SET_HOME_ID_STATUS;

/*********************************************************************************************************
 * 枚举名称 : READ_ID_SHOW_STATUS
 * 功能说明 : 读取房号后UI显示状态的枚举
 * 设计说明 : 控制读取房号数据后，是否刷新显示输入框内容
 *********************************************************************************************************/
typedef enum
{
	READ_HOME_ID_SHOW, // 显示读取到的房号（刷新输入框显示）
	READ_HOME_ID_HIDE  // 隐藏/不刷新房号显示（默认状态）
} READ_ID_SHOW_STATUS;

/*********************************************************************************************************
 * 枚举名称 : LAYER
 * 功能说明 : 房号设置界面的图层枚举
 * 设计说明 : 区分主操作图层和确认对话框图层，用于按键逻辑和UI显示的分层控制
 *********************************************************************************************************/
typedef enum
{
	LAYER_MAIN,	 // 主图层（房号输入框操作界面）
	LAYER_DIALOG // 对话框图层（房号已存在时的YES/NO确认框）
} LAYER;

/*********************************************************************************************************
 * 枚举名称 : SELECT
 * 功能说明 : 确认对话框的选中状态枚举
 * 设计说明 : 标识对话框中“是/否”选项的选中状态，用于UI高亮和逻辑判断
 *********************************************************************************************************/
typedef enum
{
	SELECT_YES, // 选中“是”（确认覆盖已存在的房号）
	SELECT_NO	// 选中“否”（取消覆盖操作）
} SELECT;

/*********************************************************************************************************
 * 结构体名称 : STR_HomeIdSetClass
 * 功能说明 : 房号设置功能的核心状态管理结构体
 * 设计说明 : 整合房号设置界面的所有状态、UI控件、数据缓存，实现集中管理
 *********************************************************************************************************/
typedef struct
{
	STR_WidgetShow widget_show;			   // UI显示接口结构体：包含字体、焦点、对话框的显示函数指针
	STR_WidgetDialogBox **dialog_box;	   // 房号输入框对话框指针数组：指向M1-M4输入框的对话框控件实例
	TouchKeyRegisterCallback key_register; // 按键注册函数指针：用于注册房号设置界面的所有按键回调
	ENUM_HOME_ID_SET_DIALOG_BOX cur_focus; // 当前焦点输入框：标识当前选中的M1-M4输入框（默认M1）
	SET_HOME_ID_STATUS set_status;		   // 房号设置状态：记录最近一次设置操作的结果（成功/失败/已存在）
	READ_ID_SHOW_STATUS read_id_show;	   // 读房号显示状态：控制是否刷新显示读取到的房号
	unsigned char show_id[4][4];		   // 输入框显示缓存：[输入框索引][数字位]，存储每个输入框的4位数字（如show_id[0][1]表示M1输入框第2位数字）
	unsigned int set_id[4];				   // 输入框最终数值：存储每个输入框拼接后的完整房号（如M1输入1234则set_id[0]=1234）
	unsigned char save_id_falg;			   // 待保存输入框标记：标识最后一次编辑、需要保存的输入框索引
	LAYER layer;						   // 当前界面图层：区分主图层/对话框图层，控制按键和显示逻辑
	STR_WidgetDialogBox *selectDialog;	   // 确认对话框指针：指向房号已存在时的YES/NO对话框控件实例
	SELECT select;						   // 对话框选中状态：标识当前选中YES/NO，用于UI高亮和确认操作

} STR_HomeIdSetClass;

/*********************************************************************************************************
 * 外部声明 : HomeIdSetClass
 * 功能说明 : 房号设置核心状态实例的外部声明
 * 用途     : 供其他模块访问/修改房号设置的状态（如UI刷新、按键处理）
 *********************************************************************************************************/
extern STR_HomeIdSetClass HomeIdSetClass;

/*********************************************************************************************************
 * 外部声明 : layout_home_id_set
 * 功能说明 : 房号设置布局实例的外部声明
 * 用途     : 供UI框架调用房号设置界面的生命周期函数（init/enter/quit/timer）
 *********************************************************************************************************/
extern layout layout_home_id_set;

#endif // LAYOUT_HOME_ID_SET_H